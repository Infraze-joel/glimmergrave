// ------------------------------------------------------------------ texts that mirror data/keystones.ts by id

function buildEnglish(): Record<string, string> {
  const out: Record<string, string> = {};
  for (const def of KEYSTONES) {
    out[`keystone.${def.id}.name`] = def.name;
    out[`keystone.${def.id}.body`] = def.summary;
    if (def.cost !== '') out[`keystone.${def.id}.cost`] = def.cost;
  }
  return out;
}

