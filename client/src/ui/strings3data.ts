/**
 * Update 3 texts that mirror the shared data tables BY ID (talents, relics, feats, reactions, set tiers,
 * Ascension stats and the descriptions of the new boons).
 *
 * English is not copied: `EN_DATA` is built from the reference strings of the tables themselves, so it can
 * never drift. German is written here. `missingTexts()` in ui/text.ts checks that every id has both and that
 * the numbers quoted in a German sentence are the numbers of its English reference.
 *
 * Keys:  talent.<id>.name|body   relic.<id>.name|body   feat.<id>.name|body   reaction.<id>.name|body
 *        set.<id>.t1|t2          paragon.<id>.body      boon.<id>.desc
 * Placeholders: {v} boon / Ascension value, {n} feat goal.
 */
import { BOONS, SETS } from '@shared/data/boons.ts';
import { FEATS } from '@shared/data/feats.ts';
import { TALENTS } from '@shared/data/mastery.ts';
import { PARAGON } from '@shared/data/meta.ts';
import { REACTIONS } from '@shared/data/reactions.ts';
import { RELICS } from '@shared/data/relics.ts';

function buildEnglish(): Record<string, string> {
  const out: Record<string, string> = {};
  for (const def of TALENTS) { out[`talent.${def.id}.name`] = def.name; out[`talent.${def.id}.body`] = def.summary; }
  for (const def of RELICS) { out[`relic.${def.id}.name`] = def.name; out[`relic.${def.id}.body`] = def.summary; }
  for (const def of FEATS) { out[`feat.${def.id}.name`] = def.name; out[`feat.${def.id}.body`] = def.summary; }
  for (const def of REACTIONS) { out[`reaction.${def.id}.name`] = def.name; out[`reaction.${def.id}.body`] = def.summary; }
  for (const def of SETS) { out[`set.${def.id}.t1`] = def.tiers[0].summary; out[`set.${def.id}.t2`] = def.tiers[1].summary; }
  for (const def of PARAGON) out[`paragon.${def.id}.body`] = def.summary;
  for (const def of BOONS) if (def.category !== 'infusion') out[`boon.${def.id}.desc`] = def.summary;
  return out;
}

