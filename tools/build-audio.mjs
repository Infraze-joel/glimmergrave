// ------------------------------------------------------------------ helpers

function ffmpeg(args, input) {
  return execFileSync(FFMPEG, ['-hide_banner', '-v', 'error', ...args], { input, maxBuffer: 1 << 28 });
}

function decode(file, rate) {
  const raw = ffmpeg(['-i', file, '-ac', '1', '-ar', String(rate), '-f', 'f32le', '-']);
  return new Float32Array(raw.buffer.slice(raw.byteOffset, raw.byteOffset + raw.byteLength));
}

function peakOf(x) {
  let peak = 0;
  for (let i = 0; i < x.length; i++) peak = Math.max(peak, Math.abs(x[i]));
  return peak;
}

const db = (lin) => 20 * Math.log10(Math.max(lin, 1e-9));
const lin = (dB) => Math.pow(10, dB / 20);

/** Second-order Butterworth high-pass, run forwards (removes DC and inaudible rumble). */
function highpass(x, rate, hz) {
  const w = (2 * Math.PI * hz) / rate;
  const alpha = Math.sin(w) / Math.SQRT2;
  const cos = Math.cos(w);
  const a0 = 1 + alpha;
  const b = [(1 + cos) / 2 / a0, -(1 + cos) / a0, (1 + cos) / 2 / a0];
  const a = [(-2 * cos) / a0, (1 - alpha) / a0];
  return biquad(x, b, a);
}

function biquad(x, b, a) {
  const y = new Float32Array(x.length);
  let x1 = 0, x2 = 0, y1 = 0, y2 = 0;
  for (let i = 0; i < x.length; i++) {
    const v = b[0] * x[i] + b[1] * x1 + b[2] * x2 - a[0] * y1 - a[1] * y2;
    x2 = x1; x1 = x[i]; y2 = y1; y1 = v;
    y[i] = v;
  }
  return y;
}

/** ITU-R BS.1770 K-weighting at 48 kHz, then the loudest window (or the whole file). */
function loudness(x48, integrated) {
  const shelf = biquad(x48, [1.53512485958697, -2.69169618940638, 1.19839281085285], [-1.69065929318241, 0.73248077421585]);
  const k = biquad(shelf, [1, -2, 1], [-1.99004745483398, 0.99007225036621]);
  const win = integrated ? k.length : Math.min(k.length, Math.floor(DSP.LOUDNESS_WINDOW_S * DSP.LOUDNESS_RATE));
  let sum = 0;
  let best = 0;
  for (let i = 0; i < k.length; i++) {
    sum += k[i] * k[i];
    if (i >= win) sum -= k[i - win] * k[i - win];
    if (i >= win - 1) best = Math.max(best, sum / win);
  }
  return -0.691 + 10 * Math.log10(Math.max(best, 1e-12));
}

function shape(x, rate, opts, bed) {
  let y = x;
  if (opts.seg) y = y.subarray(Math.floor(opts.seg[0] * rate), Math.floor((opts.seg[0] + opts.seg[1]) * rate));
  y = highpass(y, rate, DSP.HIGHPASS_HZ);
  const peak = peakOf(y);
  if (peak <= 0) throw new Error('silent source');
  if (!opts.seg) {
    const startThr = peak * lin(DSP.TRIM_START_DB);
    const endThr = peak * lin(DSP.TRIM_END_DB);
    let s = 0;
    let e = y.length - 1;
    while (s < y.length && Math.abs(y[s]) < startThr) s++;
    while (e > s && Math.abs(y[e]) < endThr) e--;
    s = Math.max(0, s - Math.floor(DSP.PRE_ROLL_S * rate));
    e = Math.min(y.length - 1, e + Math.floor(DSP.POST_ROLL_S * rate));
    y = y.slice(s, e + 1);
  } else {
    y = y.slice();
  }
  const fadeIn = Math.floor((bed ? DSP.BED_FADE_S : DSP.FADE_IN_S) * rate);
  const fadeOut = Math.floor((bed ? DSP.BED_FADE_S
    : Math.min(DSP.FADE_OUT_MAX_S, Math.max(DSP.FADE_OUT_MIN_S, (y.length / rate) * DSP.FADE_OUT_FRACTION))) * rate);
  for (let i = 0; i < Math.min(fadeIn, y.length); i++) y[i] *= i / fadeIn;
  for (let i = 0; i < Math.min(fadeOut, y.length); i++) y[y.length - 1 - i] *= i / fadeOut;
  const norm = lin(DSP.PEAK_DB) / peakOf(y);
  for (let i = 0; i < y.length; i++) y[i] *= norm;
  return y;
}

function gitHead(dir) {
  return execFileSync('git', ['-C', dir, 'rev-parse', 'HEAD']).toString().trim();
}

// ------------------------------------------------------------------ licence gate

const packInfo = {};
for (const [key, pack] of Object.entries(PACKS)) {
  const dir = join(SRC, pack.repo);
  const licenceFile = join(dir, pack.licence);
  if (!existsSync(licenceFile)) throw new Error(`${pack.repo}: licence file ${pack.licence} not found — refusing to use this pack`);
  const text = readFileSync(licenceFile, 'utf8');
  if (!CC0_MARKERS.some((re) => re.test(text))) throw new Error(`${pack.repo}: ${pack.licence} does not state CC0 — refusing to use this pack`);
  packInfo[key] = { ...pack, dir, commit: gitHead(dir) };
}

