// Files are replaced in place and stale ones removed afterwards: deleting the folder first would make a
// running Vite dev server forget its public files until it is restarted.
mkdirSync(OUT, { recursive: true });

const entries = [];
const credits = [];
for (const [group, cat, tier, files] of GROUPS) {
  const category = CATEGORIES[cat];
  files.forEach(([packKey, rel, opts = {}], index) => {
    const pack = packInfo[packKey];
    const source = join(pack.dir, pack.sub, rel);
    if (!existsSync(source)) throw new Error(`missing source ${source}`);
    const rate = opts.rate ?? DSP.RATE;
    const name = `${group}.${index + 1}`;
    const file = `${name}.mp3`;
    const pcm = shape(decode(source, rate), rate, opts, cat === 'bed');
    ffmpeg([
      '-f', 'f32le', '-ar', String(rate), '-ac', '1', '-i', 'pipe:0',
      '-codec:a', 'libmp3lame', '-q:a', String(category.q), '-map_metadata', '-1', '-id3v2_version', '0', '-write_id3v1', '0',
      '-fflags', '+bitexact', '-flags:a', '+bitexact', '-y', join(OUT, file),
    ], Buffer.from(pcm.buffer, pcm.byteOffset, pcm.byteLength));
    // Measure what ships, not what went in.
    const shipped = decode(join(OUT, file), DSP.LOUDNESS_RATE);
    const loud = loudness(shipped, category.integrated === true);
    const gain = Math.min(DSP.MAX_GAIN, lin(category.target - loud), DSP.MAX_PEAK_AFTER_GAIN / peakOf(shipped));
    const bytes = statSync(join(OUT, file)).size;
    entries.push({
      name, group, cat, tier, file,
      dur: Math.round((pcm.length / rate) * 1000) / 1000,
      gain: Math.round(gain * 1000) / 1000,
      peakDb: Math.round(db(peakOf(shipped)) * 10) / 10,
      loudness: Math.round(loud * 10) / 10,
      bytes,
    });
    credits.push({ file, pack: pack.title, source: `${pack.sub}/${rel}`, url: pack.url, commit: pack.commit });
  });
}

